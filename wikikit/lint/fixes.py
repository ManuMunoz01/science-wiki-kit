"""The three repair tools that sit behind wiki-lint: index proposals, Check 12 backlinks, promotion.

All three work on the file's own line endings (never rewriting LF to CRLF or the reverse) and never
touch anything but what they report. `promote` and `check12` log every change for rollback.
"""
import datetime
import re
from pathlib import Path

from .. import frontmatter
from ..textio import append_log, detect_eol, read_text, write_text
from . import checks_structure
from .context import Context
from .text import extract_wikilinks, split_lines

_WIKILINK = re.compile(r"\[\[([^\]|#]+?)(?:#[^\]|]+)?(?:\|([^\]]+))?\]\]")


# ---------------------------------------------------------------- index proposals

def _summary(body, max_len=220):
    """First prose paragraph of a note, links reduced to their text, cut to `max_len`."""
    lines = split_lines(body)
    buf, i = [], 0
    while i < len(lines):
        t = lines[i].strip()
        if not t or t.startswith(("#", ">", "---", "|", "!")):
            i += 1
            continue
        while i < len(lines):
            t = lines[i].strip()
            if not t or t.startswith(("#", ">")):
                break
            buf.append(t)
            if sum(len(x) + 1 for x in buf) >= max_len:
                break
            i += 1
        break
    s = " ".join(buf)
    if len(s) > max_len:
        s = s[:max_len].rstrip() + "…"
    return _WIKILINK.sub(lambda m: m.group(2) or m.group(1).replace("_", " "), s)


def index_proposal(ctx, missing_lines, today=None):
    """Markdown with the entries Check 7 found missing from index.md, grouped by Title Case subsection.

    `missing_lines` = lines `basename|folder` of `wiki_check7_index_missing.txt`. Read-only proposal:
    a person reviews it and inserts the entries into the right subsections of index.md."""
    today = today or datetime.date.today().isoformat()
    field_map = ctx.cfg.get("field_titlecase_map") or {}
    papers, books, concepts, methods = [], [], {}, {}
    for line in missing_lines:
        if not line.strip():
            continue
        base, folder = (line.split("|") + [""])[:2]
        path = ctx.wiki / folder / (base + ".md")
        if not path.is_file():
            continue
        fm, body = frontmatter.parse(read_text(path))
        field, sub = fm.get("field", ""), fm.get("subfield", "")
        tag = " [%s / %s]" % (field, sub) if (field or sub) else ""
        entry = "- [[%s]] - %s%s" % (base, _summary(body), tag)
        title = field_map.get(field if isinstance(field, str) else "") or "Uncategorized"
        f = folder.lower()
        if f == ctx.papers.lower():
            papers.append(entry)
        elif f == ctx.books.lower():
            books.append(entry)
        elif f == ctx.concepts.lower():
            concepts.setdefault(title, []).append(entry)
        elif f == ctx.methods.lower():
            methods.setdefault(title, []).append(entry)

    out = ["# Wiki Index - Proposed Additions (%s)" % today, "",
           "> Generated by `fix.py index`. Entries are grouped by Title Case subsection per "
           "`field_titlecase_map`. Review and insert into the proper subsections of `index.md`.", ""]
    if papers:
        out += ["## Papers (`%s/`)" % ctx.papers, ""] + sorted(papers) + [""]
    if books:
        out += ["## Books (`%s/`)" % ctx.books, ""] + sorted(books) + [""]
    for heading, folder, groups in (("Concepts", ctx.concepts, concepts), ("Methodology", ctx.methods, methods)):
        if groups:
            out += ["## %s (`%s/`)" % (heading, folder), ""]
            for title in sorted(groups):
                out += ["### " + title, ""] + sorted(groups[title]) + [""]
    summary = (len(papers), len(books), len(concepts), len(methods))
    return "\n".join(out) + "\n", summary


# ---------------------------------------------------------------- Check 12 backlinks

SECTION_BY_FOLDER = {"concepts": "Papers Using This Concept", "methods": "Papers Using This Method"}


def _insert_backlinks(text, section, bullets):
    """Return (new_text, where). Insert `bullets` under `## section`, creating it if absent."""
    eol = detect_eol(text)
    lines = text.split(eol)
    hdr = re.compile(r"^\s*##\s+" + re.escape(section) + r"\s*$", re.I)
    hdr_idx = next((i for i, ln in enumerate(lines) if hdr.match(ln)), -1)
    if hdr_idx >= 0:
        # After the last content line of THIS section (before the next `## `), never anchored to a terminal
        # section: notes may nest other `##` groups between the papers header and "Related Notes", and
        # anchoring past those would file the backlinks under the wrong, mis-attributing heading.
        sec_end = next((i for i in range(hdr_idx + 1, len(lines)) if re.match(r"^\s*##\s", lines[i])), len(lines))
        last = hdr_idx
        for i in range(hdr_idx + 1, sec_end):
            if lines[i].strip():
                last = i
        new = lines[:last + 1] + bullets + lines[last + 1:]
        return eol.join(new), "into existing '## %s'" % section
    block = ["## " + section, ""] + bullets + [""]
    rel = next((i for i, ln in enumerate(lines) if re.match(r"^\s*##\s+Related Notes\s*$", ln)), -1)
    if rel >= 0:
        return eol.join(lines[:rel] + block + lines[rel:]), "new '## %s' before '## Related Notes'" % section
    new = list(lines)
    if new and new[-1].strip():
        new.append("")
    return eol.join(new + block), "new '## %s' appended at EOF" % section


def fix_check12(ctx, dry_run=False, log_file=None, now=None):
    """Insert the missing `[[paper]]` backlink into every target of a Check 12 asymmetry.

    The asymmetries are computed LIVE from the notes (not from a cache file that may be stale). Policy:
    add the missing backlink in ALL cases (including `status: final`), prioritising retrieval; every
    change is logged for rollback. `missing_target` rows are not touched. Idempotent: a paper already
    wikilinked anywhere in the target body is skipped."""
    now = now or datetime.datetime.now()
    asym = checks_structure.check12(ctx).files["wiki_check12_asymmetry.txt"]
    placeholder = ctx.lcfg.get("claim_placeholder_text", "[pending claim]")
    groups = {}
    for row in asym:
        paper, token, folder = row.split("|")
        groups.setdefault((folder, token), []).append(paper)

    mode = "DRY-RUN (no files written)" if dry_run else "APPLIED"
    log = ["# Check 12 Auto-Fix Log - %s" % now.strftime("%Y-%m-%d %H:%M"), "",
           "Mode: %s  |  Target notes: %d" % (mode, len(groups)), ""]
    touched = added = skipped = 0
    for (folder, token) in sorted(groups):
        key = "%s/%s" % (folder, token)
        path = ctx.wiki / folder / (token + ".md")
        if not path.is_file():
            log.append("- %s : TARGET FILE NOT FOUND (skipped)" % key)
            continue
        text = read_text(path)
        _, body = frontmatter.parse(text)
        body_links = {t.lower() for t, _, _ in extract_wikilinks(body)}
        papers = sorted(set(groups[(folder, token)]))
        to_add = []
        for p in papers:
            if p.lower() in body_links:
                skipped += 1
            else:
                to_add.append(p)
        if not to_add:
            log.append("- %s : all %d paper(s) already linked (no-op)" % (key, len(papers)))
            continue
        section = SECTION_BY_FOLDER["concepts" if folder.lower() == ctx.concepts.lower() else "methods"]
        bullets = ["- [[%s]] - %s" % (p, placeholder) for p in to_add]
        new_text, where = _insert_backlinks(text, section, bullets)
        if not dry_run:
            write_text(path, new_text)
        touched += 1
        added += len(to_add)
        log.append("- [x] %s : +%d backlink(s) %s" % (key, len(to_add), where))
        log += ["    - [[%s]]" % p for p in to_add]
    log += ["", "Summary: notes touched=%d, backlinks added=%d, already-linked skipped=%d" % (touched, added, skipped)]
    if log_file:
        write_text(log_file, "\n".join(log) + "\n")
    return {"mode": mode, "touched": touched, "added": added, "skipped": skipped, "log": log}


# ---------------------------------------------------------------- promote

def promote(ctx, list_file, new_status="final", log_file=None, now=None):
    """Flip `status: draft` to `new_status` in the frontmatter of each listed note.

    The list holds one note per line: a path, or a bare note name (resolved in the wiki); blank lines and
    `#` comments are ignored. Only a status line inside the frontmatter that reads exactly `draft` is
    touched (line based, so CRLF files keep their line endings); anything else is reported for manual
    review. Every outcome is appended to the log."""
    now = now or datetime.datetime.now()
    entries = [ln.strip() for ln in split_lines(read_text(list_file)) if ln.strip() and not ln.strip().startswith("#")]
    log = ["# Wiki Promotion Log - %s" % now.strftime("%Y-%m-%d %H:%M"), "",
           "## Batch: status -> %s  (input: %s)" % (new_status, list_file), ""]
    changed = 0
    for entry in entries:
        path = Path(entry)
        if not path.is_file():
            hit = ctx.note(Path(entry).stem)
            path = hit.path if hit is not None else None
        if path is None or not Path(path).is_file():
            log.append("- %s : NOT FOUND" % entry)
            continue
        text = read_text(path)
        eol = detect_eol(text)
        lines = text.split(eol)
        close = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None) \
            if lines and lines[0].strip() == "---" else None
        idx = next((i for i in range(1, close or 0) if re.match(r"^status:", lines[i])), None)
        value = re.sub(r"^status:\s*", "", lines[idx]).strip().strip("\"'") if idx is not None else None
        if value is not None and value.lower() == "draft":
            lines[idx] = "status: " + new_status
            write_text(path, eol.join(lines))
            changed += 1
            log.append("- [x] %s : draft -> %s" % (entry, new_status))
        elif value is not None and value.lower() == new_status.lower():
            log.append("- [ ] %s : already %s (no-op)" % (entry, new_status))
        else:
            log.append("- [ ] %s : status not 'draft' (manual review)" % entry)
    if log_file:
        if Path(log_file).exists():
            append_log(log_file, "# Wiki Promotion Log", log[2:])
        else:
            write_text(log_file, "\n".join(log) + "\n")
    return {"changed": changed, "listed": len(entries), "log": log}
